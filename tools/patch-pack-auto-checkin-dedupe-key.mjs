/**
 * Patch channel-pack: compare history runs by what a READER sees, not by
 * internal account ids.
 *
 * MEASURED FAILURE (first real use, 2026-11-13):
 * two clicks twenty minutes apart produced three history rows instead of one
 * with `runs: 2`. `result` and `totals` were byte-identical; the only
 * difference was TRAE's `accountId`, which had drifted from `trae-feda3732` to
 * `trae-c476bfb4` for the SAME nickname with the SAME outcome ("今天已签到").
 * Re-scanning a QR code, a new device id or a rebuilt upstream pool all churn
 * that id, so de-duplication keyed on it can never collapse a steady day.
 *
 * THE FIX
 *
 * `sameHistoryRun` now compares a NORMALISED view of each row:
 *   - drop `accountId` (an internal handle the dialog never shows as identity —
 *     the nickname is what the user reads),
 *   - sort by provider + nickname + status, so channel iteration order cannot
 *     masquerade as a new outcome,
 *   - keep status / nickname / amount / unit / code / reason, which is exactly
 *     what the dialog renders. A real change (an account starts failing, an
 *     amount moves, an account is added or removed) STILL gets its own entry.
 *
 * Idempotent, marked `[xdpool-local] auto-checkin-dedupe-key`.
 * Run AFTER patch-pack-auto-checkin-retry-policy.mjs.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const PATH = 'vendor/channel-pack/pack.js'
const MARKER = '[xdpool-local] auto-checkin-dedupe-key'

const source = readFileSync(PATH, 'utf8')
if (source.includes(MARKER)) {
  console.log('already patched')
  process.exit(0)
}

const EOL = source.includes('\r\n') ? '\r\n' : '\n'
const lines = source.split(/\r?\n/)

function replaceBlock(anchor, count, block) {
  const index = lines.findIndex(line => line === anchor)
  if (index === -1) throw new Error('anchor not found: ' + anchor.slice(0, 90))
  lines.splice(index, count, ...block)
}

// Replace the whole sameHistoryRun function (7 lines as generated by the
// retry-policy patch).
replaceBlock(
  'function sameHistoryRun(a, b) {',
  7,
  [
    '// ' + MARKER + ': compare what the dialog SHOWS, not the internal account id.',
    '//',
    '// TRAE (and any QR-linked channel) can re-mint an account id for the same',
    '// nickname between two runs — measured as trae-feda3732 -> trae-c476bfb4 on',
    '// an unchanged "今天已签到". Keying on that id made every steady day look',
    '// like a new run, which is the opposite of what this exists to prevent.',
    'function historyRowKey(row) {',
    '  if (row === null || typeof row !== "object") return "";',
    '  // Deliberately NO accountId: it is an internal handle, and it drifts.',
    '  return [',
    '    String(row.provider ?? ""),',
    '    String(row.nickname ?? ""),',
    '    String(row.status ?? ""),',
    '    String(row.amount ?? ""),',
    '    String(row.unit ?? ""),',
    '    String(row.code ?? ""),',
    '    String(row.reason ?? ""),',
    '  ].join("\\u0001");',
    '}',
    'function historyDetailsKey(details) {',
    '  if (!Array.isArray(details)) return "";',
    '  // Sort first: providers are iterated in whatever order the pool lists',
    '  // them, and a reordering is not a new outcome.',
    '  return details.map(historyRowKey).sort().join("\\u0002");',
    '}',
    'function sameHistoryRun(a, b) {',
    '  if (a === null || typeof a !== "object") return false;',
    '  // `at` and `runs` are bookkeeping; the outcome is the rest.',
    '  return a.result === b.result',
    '    && JSON.stringify(a.totals ?? {}) === JSON.stringify(b.totals ?? {})',
    '    && historyDetailsKey(a.details) === historyDetailsKey(b.details);',
    '}',
  ],
)

const text = lines.join(EOL)
if (!text.includes(MARKER)) throw new Error('marker did not land')
if (!text.includes('function historyRowKey(row)')) throw new Error('row key missing')
if (!text.includes('function historyDetailsKey(details)')) throw new Error('details key missing')
if (!text.includes('historyDetailsKey(a.details) === historyDetailsKey(b.details)')) throw new Error('comparison not rewired')
if (text.includes('&& JSON.stringify(a.details ?? []) === JSON.stringify(b.details ?? []);')) {
  throw new Error('old raw comparison still present')
}
writeFileSync(PATH, text)
console.log('patched: history de-duplication ignores the drifting account id')
